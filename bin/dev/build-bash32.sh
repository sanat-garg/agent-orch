#!/usr/bin/env bash
# Builds bash 3.2.57, the /bin/bash every Mac ships, into ~/.local/opt/bash-3.2.57/bin/bash for
# test/install-macos-bash32.test.mjs (skipped without it). The worker installers run under it on a Mac
# (`curl … | sudo bash`), and the bash 5 on this server hides its bugs: `declare -f` printing `cmd <<EOF | next`
# with the `| next` after EOF, and set -u calling an empty "${arr[@]}" unbound.
# Usage: bin/dev/build-bash32.sh [--force]   (installs bison with sudo apt-get when it is missing)
set -euo pipefail

VER=3.2.57
SHA256=3fa9daf85ebf35068f090ce51283ddeeb3c75eb5bc70b1a4a7cb05868bfe06a4
URL=https://ftp.gnu.org/gnu/bash/bash-$VER.tar.gz
DEST="$HOME/.local/opt/bash-$VER/bin/bash"
# gcc 15 defaults to C23 and rejects this 2007 K&R C: build it as gnu89 with the modern errors turned back into warnings.
F='-O1 -std=gnu89 -Wno-implicit-function-declaration -Wno-implicit-int -Wno-int-conversion -Wno-incompatible-pointer-types -Wno-error'

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
case "${1:-}" in
  --force|'') ;;
  *) echo "usage: $0 [--force]" >&2; exit 2 ;;
esac
if [[ "${1:-}" != --force && -x "$DEST" ]] && [[ "$("$DEST" -c 'echo $BASH_VERSION')" == "$VER"* ]]; then
  say "$DEST is already bash $VER (--force rebuilds it)"; exit 0
fi
# An earlier by-hand build (task #244) left one here; reuse it rather than spend minutes rebuilding.
PREV=/tmp/b32/bash-$VER/bash
if [[ "${1:-}" != --force && -x "$PREV" ]] && [[ "$("$PREV" -c 'echo $BASH_VERSION')" == "$VER"* ]]; then
  mkdir -p "$(dirname "$DEST")"; install -m 0755 "$PREV" "$DEST"
  say "Copied $PREV to $DEST"; exit 0
fi

command -v bison >/dev/null || { say "Installing bison"; sudo apt-get install -y bison; }
work="$(mktemp -d "${TMPDIR:-/tmp}/build-bash32.XXXXXX")"
trap 'rm -rf "$work"' EXIT
say "Downloading $URL"
curl -fsSL "$URL" -o "$work/bash.tar.gz"
echo "$SHA256  $work/bash.tar.gz" | sha256sum -c --quiet -
tar -xzf "$work/bash.tar.gz" -C "$work"
cd "$work/bash-$VER"
# The shipped parser was generated by a 2007 yacc; let bison regenerate it.
rm -f y.tab.c y.tab.h
say "Building (a few minutes)"
# Its config.guess predates aarch64, so name the build machine. configure's probes need the flags too (without them
# it misses strsignal and siglist.c fails).
./configure --build="$(uname -m)-unknown-linux-gnu" --without-bash-malloc --disable-nls CFLAGS="$F" >"$work/build.log" 2>&1 \
  && make CFLAGS="$F" CFLAGS_FOR_BUILD="$F" >>"$work/build.log" 2>&1 \
  || { tail -30 "$work/build.log"; exit 1; }
mkdir -p "$(dirname "$DEST")"
install -m 0755 bash "$DEST"
say "Installed $DEST: $("$DEST" --version | head -1)"
